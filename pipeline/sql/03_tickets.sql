CREATE OR REPLACE TABLE tickets AS
SELECT
    ticket_number,
    min(month)                       AS month,
    min(ticket_type)                 AS ticket_type,
    min(stop_ts)                     AS stop_ts,
    min(county_name)                 AS county_name,
    min(officer_id)                  AS officer_id,
    min(service)                     AS service,
    min(region)                      AS region,
    min(district)                    AS district,
    min(road_class)                  AS road_class,
    min(route)                       AS route,
    max(latitude)                    AS latitude,
    max(longitude)                   AS longitude,
    min(driver_race_sex)             AS driver_race_sex,
    min(vehicle_type)                AS vehicle_type,
    min(vehicle_make)                AS vehicle_make,
    min(vehicle_year)                AS vehicle_year,
    min(vehicle_color)               AS vehicle_color,
    min(special_program)             AS special_program,
    bool_or(commercial_vehicle)      AS commercial_vehicle,
    bool_or(driver_cdl)              AS driver_cdl,
    bool_or(fugitive)                AS fugitive,
    bool_or(race_known_prior)        AS race_known_prior,
    bool_or(accident)                AS accident,
    bool_or(construction_zone)       AS construction_zone,
    count(*)                                              AS n_violation_records,
    count(*) FILTER (WHERE violation_type = 'Citation')  AS n_citations,
    count(*) FILTER (WHERE violation_type = 'Warning')   AS n_warnings,
    bool_or(searched)                  AS searched,
    bool_or(search_consent)            AS search_consent,
    bool_or(search_probable_cause)     AS search_probable_cause,
    bool_or(search_incident_to_arrest) AS search_incident_to_arrest,
    bool_or(search_inventory)          AS search_inventory,
    bool_or(contraband_found)          AS contraband_found,
    bool_or(contraband_drugs)          AS contraband_drugs,
    bool_or(contraband_weapons)        AS contraband_weapons,
    bool_or(contraband_currency)       AS contraband_currency,
    bool_or(contraband_other)          AS contraband_other
FROM violations
GROUP BY ticket_number;
