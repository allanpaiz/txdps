CREATE OR REPLACE TABLE violations AS
SELECT
    source_row_id,
    source_month                                               AS month,
    Ticket_Number                                              AS ticket_number,
    Ticket_Type                                                AS ticket_type,
    strptime(Datetime, '%Y-%m-%d %H:%M:%S')                    AS stop_ts,
    CASE WHEN County = 'Dewitt' THEN 'De Witt' ELSE County END AS county_name,
    nullif(trim(Officer_ID), '')                                           AS officer_id,
    Service                                                    AS service,
    Region                                                     AS region,
    District                                                   AS district,
    Road_Class                                                 AS road_class,
    nullif(trim(Route), '')                                    AS route,
    CASE WHEN TRY_CAST(Latitude AS DOUBLE)  BETWEEN 25.8 AND 36.6
          AND TRY_CAST(Longitude AS DOUBLE) BETWEEN -106.7 AND -93.4
         THEN TRY_CAST(Latitude AS DOUBLE)  END                AS latitude,
    CASE WHEN TRY_CAST(Latitude AS DOUBLE)  BETWEEN 25.8 AND 36.6
          AND TRY_CAST(Longitude AS DOUBLE) BETWEEN -106.7 AND -93.4
         THEN TRY_CAST(Longitude AS DOUBLE) END                AS longitude,
    Driver_Race_Sex                                            AS driver_race_sex,
    nullif(trim(Vehicle_Type), '')                             AS vehicle_type,
    Vehicle_Make                                               AS vehicle_make,
    nullif(TRY_CAST(Vehicle_Year AS INTEGER), 0)               AS vehicle_year,
    Vehicle_Color                                              AS vehicle_color,
    nullif(trim(Special_Program_Name), '')                     AS special_program,
    upper(Commercial_Vehicle)        = 'YES'                   AS commercial_vehicle,
    upper(Driver_CDL_Holder)         = 'YES'                   AS driver_cdl,
    upper(Fugitive)                  = 'YES'                   AS fugitive,
    upper(Race_Known_Prior)          = 'YES'                   AS race_known_prior,
    upper(Accident)                  = 'YES'                   AS accident,
    upper(Construction_Zone)         = 'YES'                   AS construction_zone,
    upper(Searched)                  = 'YES'                   AS searched,
    upper(Search_Consent)            = 'YES'                   AS search_consent,
    upper(Search_Prob_Cause)         = 'YES'                   AS search_probable_cause,
    upper(Search_Incident_to_Arrest) = 'YES'                   AS search_incident_to_arrest,
    upper(Search_Vehicle_Inventory)  = 'YES'                   AS search_inventory,
    upper(Contraband_Found)          = 'YES'                   AS contraband_found,
    upper(Contraband_Drugs_Found)    = 'YES'                   AS contraband_drugs,
    upper(Contraband_Weapons_Found)  = 'YES'                   AS contraband_weapons,
    upper(Contraband_Currency_Found) = 'YES'                   AS contraband_currency,
    upper(Contraband_Other_Found)    = 'YES'                   AS contraband_other,
    nullif(TRY_CAST(Posted_Speed  AS INTEGER), 0)              AS posted_speed,
    TRY_CAST(Alleged_Speed AS INTEGER)                         AS alleged_speed,
    Violation_Type                                             AS violation_type,
    Violation_Category                                         AS violation_category,
    Violation_Code                                             AS violation_code,
    Violation_Name                                             AS violation_name
FROM raw_violations;
